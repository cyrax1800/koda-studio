package org.kotlinlsp

import org.eclipse.lsp4j.*
import org.eclipse.lsp4j.services.LanguageClient
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test
import org.kotlinlsp.lsp.KotlinLanguageServer
import org.kotlinlsp.lsp.KotlinLanguageServerNotifier
import org.mockito.Mockito.mock
import java.io.File
import java.nio.file.Files

/**
 * Find references counts uses in Java files (hand-written, or generated by Hilt/Dagger) and in KDoc links, and leaves
 * the declaration out when the client asks for usages only.
 */
class JavaReferences {
    private val stdlibJar: File? = File(System.getProperty("user.home"), ".gradle/caches/modules-2/files-2.1/org.jetbrains.kotlin/kotlin-stdlib")
        .walkTopDown().firstOrNull { it.name.matches(Regex("kotlin-stdlib-2\\.[0-9.]+\\.jar")) }

    @Test
    fun `finds usages in Java files and KDoc`() {
        val stdlib = stdlibJar ?: return // nothing to test without the jar in the Gradle cache
        val root = Files.createTempDirectory("javarefs").toFile()
        fun source(path: String, text: String) = File(root, path).apply {
            parentFile.mkdirs()
            writeText(text)
        }
        val model = source("model/demo/Model.kt", "package demo\n\nclass Model(val id: Int)\n")
        source("app/demo/Uses.kt", "package demo\n\n/** Wraps a [Model]. */\nfun wrap(model: Model): Model = Model(model.id)\n")
        source("app/demo/Factory.java", "package demo;\n\npublic final class Factory {\n  public static Model create(int id) {\n    return new Model(id);\n  }\n}\n")
        source("app/demo/Unrelated.java", "package demo;\n\npublic final class Unrelated {\n  String Model = \"not a type\";\n}\n")
        fun module(id: String, vararg dependencies: String) =
            """{"id": "$id", "dependencies": [${(dependencies.toList() + listOf("stdlib", "jdk")).joinToString { "\"$it\"" }}], "javaVersion": "17", "contentRoots": ["${File(root, id)}"], "isSource": true, "kotlinVersion": "2.2"}"""
        val modules = File(root, "modules.json").apply {
            writeText(
                """
                [
                  ${module("app", "model")},
                  ${module("model")},
                  {"id": "stdlib", "dependencies": ["jdk"], "javaVersion": "17", "contentRoots": ["${stdlib.absolutePath}"], "isSource": false, "isJdk": false},
                  {"id": "jdk", "dependencies": [], "javaVersion": "17", "isJdk": true, "isSource": false, "contentRoots": ["${System.getProperty("java.home")}"]}
                ]
                """.trimIndent()
            )
        }

        val server = KotlinLanguageServer(mock(KotlinLanguageServerNotifier::class.java))
        server.connect(mock(LanguageClient::class.java))
        server.initialize(InitializeParams().apply {
            workspaceFolders = listOf(WorkspaceFolder("file://${root.absolutePath}", "root"))
            initializationOptions = com.google.gson.JsonObject().apply {
                addProperty("modulesFile", modules.absolutePath)
                addProperty("indexDir", File(root, "index").absolutePath)
            }
        }).join()
        server.initialized(InitializedParams())
        try {
            val uri = "file://${model.absolutePath}"
            server.didOpen(DidOpenTextDocumentParams(TextDocumentItem(uri, "kotlin", 1, model.readText())))
            fun references(includeDeclaration: Boolean) = server.references(ReferenceParams(
                TextDocumentIdentifier(uri), Position(2, 7), ReferenceContext(includeDeclaration),
            )).join().orEmpty().map { "${File(it.uri.removePrefix("file://")).name}:${it.range.start.line}" }.sorted()

            // Uses.kt: KDoc link (line 2), parameter type, return type and constructor call (line 3); Factory.java: return
            // type (line 3) and `new Model` (line 4). The string field named Model in Unrelated.java is not a use.
            assertEquals(
                listOf("Factory.java:3", "Factory.java:4", "Uses.kt:2", "Uses.kt:3", "Uses.kt:3", "Uses.kt:3"),
                references(includeDeclaration = false),
            )
            assertEquals(true, "Model.kt:2" in references(includeDeclaration = true))
        } finally {
            server.shutdown().join()
            root.deleteRecursively()
        }
    }
}
