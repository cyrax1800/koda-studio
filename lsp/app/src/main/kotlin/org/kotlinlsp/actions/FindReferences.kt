private data class SymbolData(
    val pointer: KaSymbolPointer<KaDeclarationSymbol>,
    val name: String,
    /** The declaration's source, to recognise it in Java files; null for library declarations. */
    val psi: PsiElement?,
)

/**
 * Usages of the declaration at [position]. Each file is analysed under its own read lock, so edits (which need the
 * write lock) get in between files instead of waiting for the whole search; [checkCanceled] stops it between files
 * once the client has cancelled it, e.g. a CodeLens for code that has scrolled away.
 */
fun findReferencesAction(
    project: Project,
    ktFile: KtFile,
    position: Position,
    index: Index,
    includeDeclaration: Boolean = true,
    checkCanceled: () -> Unit = {},
): List<Location>? {
    // Get the symbol at the current position and create a pointer for efficient comparison
    val targetData = project.read {
        val offset = position.toOffset(ktFile)
        val ktElement = ktFile.findElementAt(offset)?.parentOfType<KtElement>() ?: return@read null
        analyze(ktElement) {
        val symbol = when (ktElement) {
            is KtDeclaration -> ktElement.symbol
            else -> ktElement.mainReference?.resolveToSymbol() as? KaDeclarationSymbol
        } ?: return@analyze null

        val symbolPointer = symbol.createPointer()
        // Get symbol name for pre-filtering files
        val symbolName = when (ktElement) {
            is KtDeclaration -> ktElement.name
            else -> ktElement.text
        } ?: return@analyze null

        SymbolData(symbolPointer, symbolName, symbol.psi)
        }
    } ?: return null

    val targetSymbolPointer = targetData.pointer
    val targetSymbolName = targetData.name
    val references = ConcurrentLinkedQueue<Location>()

    // Every file that mentions the name, then resolve: declaration files alone miss nearly all usages.
    val filesToSearch = project.read { index.sourceFilesMentioning(targetSymbolName) }

    runBlocking {
        filesToSearch.map { file ->
            async(CustomDispatcher.cpu) {
                try {
                    checkCanceled()
                    val fileReferences = project.read { findReferencesInFile(file, targetSymbolPointer, targetSymbolName, includeDeclaration) }
                    references.addAll(fileReferences)
                } catch (e: CancellationException) {
                    throw e
                } catch (e: Exception) {
                    // Silently ignore resolution errors for robustness
                }
            }
        }.awaitAll()
    }
    // Java code using it: hand-written, or generated by Hilt, Dagger or Room (as Android Studio counts them).
    targetData.psi?.let { target ->
        for (javaFile in project.read { index.javaFilesMentioning(targetSymbolName) }) {
            checkCanceled()
            try {
                references.addAll(project.read { findJavaReferences(javaFile, target, targetSymbolName) })
            } catch (e: Throwable) {
                // A Java file that doesn't resolve shouldn't fail the whole search. IntelliJ reports invalid PSI as an
                // AssertionError, which an `Exception` catch let through.
                if (org.kotlinlsp.common.isCancellation(e)) throw e
            }
        }
    }

    return references.toList().ifEmpty { null }
}

/**
 * Get list of files to search, pre-filtered by symbol name
 */
private fun findReferencesInFile(
    ktFile: KtFile,
    targetSymbolPointer: KaSymbolPointer<KaDeclarationSymbol>,
    targetName: String,
    includeDeclaration: Boolean,
): List<Location> {
    val references = mutableListOf<Location>()
    
    analyze(ktFile) {
        val targetSymbol = targetSymbolPointer.restoreSymbol() ?: return@analyze
        // Only references spelled like the target (or an import alias of it) can be uses, so only those are resolved:
        // resolving every reference made a search for a type used in 440 files take two minutes. Operator conventions
        // (`a + b` calls `plus`, `a[i]` calls `get`) are used without their name, so for those everything is resolved.
        val names = setOf(targetName) + ktFile.importDirectives
            .filter { it.importedFqName?.shortName()?.asString() == targetName }
            .mapNotNull { it.aliasName }
        val operator = targetName in OPERATOR_NAMES || Regex("component[0-9]+").matches(targetName)
        // Code references, and KDoc links such as `[Pokemon]`.
        val referenceExpressions: List<KtElement> = (ktFile.collectDescendantsOfType<KtReferenceExpression>() + ktFile.collectDescendantsOfType<KDocName>())
            .filter { element ->
                operator || when (element) {
                    is KtSimpleNameExpression -> element.getReferencedName() in names
                    is KDocName -> element.getNameText() in names
                    else -> false
                }
            }

        for (refExpr in referenceExpressions) {
            try {
                val reference = when (refExpr) {
                    is KtReferenceExpression -> refExpr.mainReference
                    is KDocName -> refExpr.mainReference
                    else -> null
                } ?: continue
                val resolvedSymbol = reference.resolveToSymbol() as? KaDeclarationSymbol
                // `Pokemon(…)` resolves to the constructor; like Android Studio, count it as a usage of the class.
                val matches = resolvedSymbol != null && (resolvedSymbol == targetSymbol ||
                    (resolvedSymbol is org.jetbrains.kotlin.analysis.api.symbols.KaConstructorSymbol && resolvedSymbol.containingSymbol == targetSymbol))
                if (matches) {
                    references.add(Location().apply {
                        uri = ktFile.virtualFile.url.normalizeUri()
                        range = refExpr.textRange.toLspRange(ktFile)
                    })
                }
            } catch (e: Exception) {
                // Silently ignore resolution errors for individual references
            }
        }
        
        // The declaration itself, unless the client asked for usages only (`includeDeclaration: false`).
        val declarations = if (includeDeclaration) ktFile.collectDescendantsOfType<KtDeclaration>() else emptyList()
        for (decl in declarations) {
            try {
                val declSymbol = decl.symbol as? KaDeclarationSymbol
                if (declSymbol != null && declSymbol == targetSymbol) {
                    val name = (decl as? PsiNameIdentifierOwner)?.nameIdentifier ?: decl
                    references.add(Location().apply {
                        uri = ktFile.virtualFile.url.normalizeUri()
                        range = name.textRange.toLspRange(ktFile)
                    })
                }
            } catch (e: Exception) {
                // Silently ignore resolution errors for individual declarations
            }
        }
    }
    
    return references
}

/**
 * References to [target] (a Kotlin declaration) in a Java file, found by resolving each reference with the matching
 * name through Java PSI: Kotlin classes and members appear there as light classes whose origin is the declaration.
 * A constructor call counts as a use of its class, as in Kotlin. Properties used through `getX()`/`setX()` aren't
 * matched, since their Java names differ.
 */
private fun findJavaReferences(javaFile: PsiJavaFile, target: PsiElement, name: String): List<Location> {
    val text = javaFile.text
    return PsiTreeUtil.collectElementsOfType(javaFile, PsiJavaCodeReferenceElement::class.java)
        .filter { it.referenceName == name }
        .filter { reference ->
            val resolved = reference.resolve() ?: return@filter false
            val origin = kotlinOrigin(resolved) ?: (resolved as? PsiMethod)?.takeIf { it.isConstructor }?.containingClass?.let(::kotlinOrigin)
            origin == target
        }
        .map { reference ->
            val range = reference.referenceNameElement?.textRange ?: reference.textRange
            Location(javaFile.virtualFile.url.normalizeUri(), Range(position(text, range.startOffset), position(text, range.endOffset)))
        }
}

private fun kotlinOrigin(element: PsiElement): PsiElement? =
    (element as? KtLightElement<*, *>)?.kotlinOrigin ?: element.navigationElement.takeIf { it is KtElement }

private fun position(text: String, offset: Int): Position =
    StringUtil.offsetToLineColumn(text, offset).let { Position(it.line, it.column) }

/** Functions called through operator syntax or conventions rather than by name. */
private val OPERATOR_NAMES = setOf(
    "plus", "minus", "times", "div", "rem", "mod", "rangeTo", "rangeUntil", "contains", "get", "set", "invoke",
    "compareTo", "equals", "inc", "dec", "unaryPlus", "unaryMinus", "not", "plusAssign", "minusAssign", "timesAssign",
    "divAssign", "remAssign", "getValue", "setValue", "provideDelegate", "iterator", "next", "hasNext",
)
